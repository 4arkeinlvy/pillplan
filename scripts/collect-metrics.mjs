// Measures the production build and test suites, and writes CSV/TeX files
// that the LaTeX documentation reads for its charts. Run after `npm run build`.
import { execSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { brotliCompressSync, gzipSync } from 'node:zlib';

const root = new URL('..', import.meta.url).pathname;
const assets = join(root, 'web/dist/assets');
const out = join(root, 'docs/tex/generated');
const files = readdirSync(assets);
const kb = (bytes) => (bytes / 1024).toFixed(1);
const gz = (file) => gzipSync(readFileSync(join(assets, file)), { level: 9 }).length;
const sum = (list, size) => list.reduce((total, file) => total + size(file), 0);
const pick = (pattern) => files.filter((file) => pattern.test(file));

const initialJs = pick(/^index-.*\.js$/);
const css = pick(/\.css$/);
const fonts = pick(/-latin-(400|700)-normal-.*\.woff2$/);
const lazy = pick(/^(catalog|counseling)-.*\.js$/);

const rows = [
  ['Initial JS', sum(initialJs, gz), 110 * 1024],
  ['CSS', sum(css, gz), 15 * 1024],
  ['Fonts', sum(fonts, (f) => statSync(join(assets, f)).size), 60 * 1024],
  ['Lazy chunks', sum(lazy, gz), 30 * 1024],
];
writeFileSync(
  join(out, 'bundle.csv'),
  'part,actual,budget\n' + rows.map(([n, a, b]) => `${n},${kb(a)},${kb(b)}`).join('\n') + '\n',
);

const brotli = sum(initialJs, (f) => brotliCompressSync(readFileSync(join(assets, f))).length);
const report = join(root, 'web/node_modules/.tmp/vitest.json');
execSync(`npx vitest run --reporter=json --outputFile=${report}`, {
  cwd: join(root, 'web'),
  stdio: 'ignore',
});
const vitest = JSON.parse(readFileSync(report, 'utf8'));
const pytest = execSync('uv run pytest -q', { cwd: join(root, 'tools'), encoding: 'utf8' });
const pyPassed = Number(/(\d+) passed/.exec(pytest)?.[1] ?? 0);
const webFiles = vitest.testResults.length;

writeFileSync(
  join(out, 'metrics.tex'),
  [
    '% Generated by scripts/collect-metrics.mjs. Do not edit by hand.',
    `\\newcommand{\\MetricInitialJsGzip}{${kb(rows[0][1])}}`,
    `\\newcommand{\\MetricInitialJsBrotli}{${kb(brotli)}}`,
    `\\newcommand{\\MetricCssGzip}{${kb(rows[1][1])}}`,
    `\\newcommand{\\MetricFonts}{${kb(rows[2][1])}}`,
    `\\newcommand{\\MetricLazyGzip}{${kb(rows[3][1])}}`,
    `\\newcommand{\\MetricWebTests}{${vitest.numPassedTests}}`,
    `\\newcommand{\\MetricWebTestFiles}{${webFiles}}`,
    `\\newcommand{\\MetricPyTests}{${pyPassed}}`,
    `\\newcommand{\\MetricAllTests}{${vitest.numPassedTests + pyPassed}}`,
    '',
  ].join('\n'),
);
console.log(rows.map(([n, a, b]) => `${n}: ${kb(a)} KB of ${kb(b)} KB`).join('\n'));
console.log(`tests: web ${vitest.numPassedTests}, python ${pyPassed}`);
